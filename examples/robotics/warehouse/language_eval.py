def fixture_scene() -> SceneGraph:
    scene = SceneGraph()
    for identity, kind, color, x, y in (
        ("parcel_0", "parcel", "blue", 0.0, 0.0),
        ("parcel_1", "parcel", "orange", 1.0, 0.0),
        ("parcel_2", "parcel", "orange", 2.0, 0.0),
        ("receiver_0", "station", "magenta", 0.0, 1.0),
        ("receiver_1", "station", "magenta", 1.0, 1.0),
    ):
        scene.upsert(
            Entity(
                identity,
                kind,
                {"color": color},
                (x, y, 0.8),
                10.0,
                "authored-parser-fixture",
                uncertainty_m=0.005,
            )
        )
    return scene


def score(case: dict, result: dict) -> bool:
    if result.get("status") != case["status"]:
        return False
    if "entity" in case:
        return result.get("entity_ids") == [case["entity"]]
    if "pairs" in case:
        tasks = result.get("tasks", [])
        if [[t["object_id"], t["destination_id"]] for t in tasks] != case["pairs"]:
            return False
        if case.get("composition") == "parallel":
            return all(not t["dependencies"] for t in tasks)
        if case.get("composition") == "sequence":
            return not tasks[0]["dependencies"] and tasks[1]["dependencies"] == [
                tasks[0]["id"]
            ]
    return True


def grammar_result(text: str, scene: SceneGraph) -> dict:
    try:
        tree = parse_instruction(text)
        return {
            "status": "supported",
            "tasks": [asdict(t) for t in ground_instruction(tree, scene, 10.0)],
        }
    except GroundingError as exc:
        return {
            "status": exc.status,
            "reason": str(exc),
            "candidates": list(exc.candidates),
        }
    except ValueError:
        return asdict(answer_question(text, scene, 10.0))


def normalized(value):
    return json.loads(json.dumps(value))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--freeze-only", action="store_true")
    parser.add_argument("--prompt-version", choices=("v1", "v2"), default="v1")
    parser.add_argument(
        "--challenge",
        action="store_true",
        help="Use the new frozen v2 challenge instead of reused development requests",
    )
    parser.add_argument(
        "--replay",
        action="store_true",
        help="Recompute grounding/scores from retained raw model output; no model inference",
    )
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    cases = (
        CASES
        if args.prompt_version == "v1"
        else [{**c, "split": "development_reuse"} for c in CASES]
    )
    if args.challenge:
        if args.prompt_version != "v2":
            parser.error("--challenge requires --prompt-version v2")
        cases = V2_CHALLENGE
    prompt = SYSTEM_PROMPT if args.prompt_version == "v1" else V2_SYSTEM_PROMPT
    cases_text = json.dumps(cases, indent=2) + "\n"
    prompt_sha = hashlib.sha256(prompt.encode()).hexdigest()
    cases_sha = hashlib.sha256(cases_text.encode()).hexdigest()
    freeze = {
        "model": MODEL_ID,
        "revision": MODEL_REVISION,
        "system_prompt_sha256": prompt_sha,
        "cases_sha256": cases_sha,
        "case_count": len(cases),
        "decoding": "greedy, max_new_tokens=384",
        "scene": fixture_scene().to_dict(),
        "scope": "Authored fixed parser/resolver fixture; no training, no robot sensor results",
    }
    freeze_path = args.output / "freeze.json"
    if freeze_path.exists() and json.loads(freeze_path.read_text()) != normalized(
        freeze
    ):
        raise ValueError(
            "Evaluation prompt/cases changed after freeze; use a new output directory"
        )
    freeze_path.write_text(json.dumps(freeze, indent=2) + "\n")
    (args.output / "cases.json").write_text(cases_text)
    (args.output / "system_prompt.txt").write_text(prompt)
    if args.freeze_only:
        return
    cached = None
    if args.replay:
        cached = json.loads((args.output / "predictions.json").read_text())
        if len(cached) != len(cases) or any(
            any(row.get(key) != value for key, value in case.items())
            for row, case in zip(cached, cases, strict=True)
        ):
            raise ValueError(
                "Retained predictions do not match complete frozen case set"
            )
    elif (args.output / "predictions.json").exists():
        raise ValueError("Refusing to overwrite model predictions")
    model = None if cached is not None else FrozenLanguageModel()
    scene = fixture_scene()
    rows = []
    for index, case in enumerate(cases):
        proposal = (
            ModelProposal(**cached[index]["proposal"])
            if cached is not None
            else model.propose(case["text"], prompt)
        )
        try:
            request = decode_request(proposal.raw_text)
            result = ground_request(request, scene, 10.0)
            admission = check_semantic_admission(case["text"], request)
        except (ValueError, TypeError, KeyError) as exc:
            result = {"status": "invalid_model_output", "reason": str(exc)}
            admission = {"status": "rejected", "stage": "schema", "reasons": [str(exc)]}
        result = normalized(result)
        grammar = normalized(grammar_result(case["text"], scene))
        row = {
            **case,
            "proposal": asdict(proposal),
            "result": result,
            "semantic_admission": admission,
            "correct": score(case, result),
            "grammar_result": grammar,
            "grammar_correct": score(case, grammar),
        }
        rows.append(row)
        (args.output / "predictions.json").write_text(json.dumps(rows, indent=2) + "\n")
        print(
            json.dumps(
                {
                    "id": case["id"],
                    "correct": row["correct"],
                    "status": result["status"],
                    "seconds": proposal.seconds,
                }
            ),
            flush=True,
        )
    summary = {
        **freeze,
        "python": platform.python_version(),
        "raw_proposals_sha256": hashlib.sha256(
            json.dumps([r["proposal"] for r in rows], sort_keys=True).encode()
        ).hexdigest(),
        "results": {
            split: {
                "count": sum(r["split"] == split for r in rows),
                "model_correct": sum(
                    r["split"] == split and r["correct"] for r in rows
                ),
                "grammar_correct": sum(
                    r["split"] == split and r["grammar_correct"] for r in rows
                ),
            }
            for split in sorted({r["split"] for r in rows})
        },
        "failures": [r["id"] for r in rows if not r["correct"]],
        "authored_guard_rejections": [
            r["id"]
            for r in rows
            if r["semantic_admission"]["status"] == "rejected"
            and r["semantic_admission"].get("stage") != "schema"
        ],
        "schema_rejections": [
            r["id"] for r in rows if r["result"]["status"] == "invalid_model_output"
        ],
        "limitations": [
            "Small authored challenge set, not a general-intelligence benchmark",
            "Perfect authored scene evidence used only to isolate parser behavior",
            "Model has no scene access and cannot answer from its own beliefs",
            "Schema validation cannot prove that a valid tree preserves language meaning",
        ],
    }
    (args.output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")


if __name__ == "__main__":
    main()
